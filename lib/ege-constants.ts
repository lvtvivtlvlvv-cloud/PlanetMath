/**
 * Detect task number from text keywords if not explicitly numbered 1..19
 */
export function detectTaskNumberByKeywords(text: string): number {
  const lower = text.toLowerCase();

  if (lower.includes("параметр") || lower.includes("значениях а ") || lower.includes("значениях a ") || lower.includes("при каких а") || lower.includes("при каких a")) {
    return 18;
  }
  if (lower.includes("кредит") || lower.includes("банк") || lower.includes("долг") || lower.includes("аннуитет") || lower.includes("дифференцирован") || lower.includes("вклад")) {
    return 16;
  }
  if (lower.includes("вектор") || lower.includes("скалярн") || lower.includes("координаты вект")) {
    return 2;
  }
  if (lower.includes("вероятност") || lower.includes("стрелок") || lower.includes("монет") || lower.includes("кубик") || lower.includes("жреби")) {
    return lower.includes("условн") || lower.includes("гипотез") || lower.includes("шахматист") || lower.includes("артиллерийск") ? 5 : 4;
  }
  if (lower.includes("производн") || lower.includes("касательн") || lower.includes("первообразн") || lower.includes("физический смысл") || lower.includes("материальная точка")) {
    return 8;
  }
  if (lower.includes("наибольшее значение") || lower.includes("наименьшее значение") || lower.includes("точку минимума") || lower.includes("точку максимума")) {
    return 12;
  }
  if (lower.includes("график функции") || lower.includes("гипербол") || lower.includes("парабол") || lower.includes("f(x) = ") || lower.includes("f(x)=") || lower.includes("найдите f(")) {
    return 11;
  }
  if (lower.includes("из пункта а в пункт б") || lower.includes("теплоход") || lower.includes("моторная лодка") || lower.includes("труба наполняет") || lower.includes("сплав") || lower.includes("раствор")) {
    return 10;
  }
  if (lower.includes("косинус") || lower.includes("синус") || lower.includes("тангенс") || lower.includes("cos") || lower.includes("sin") || lower.includes("tg")) {
    if (lower.includes("укажите корни") || lower.includes("отбор корней") || lower.includes("принадлежащие отрезку")) {
      return 13;
    }
  }
  if (lower.includes("пирамид") || lower.includes("призм") || lower.includes("конус") || lower.includes("цилиндр") || lower.includes("шар") || lower.includes("многогранник")) {
    return lower.includes("докажите") || lower.includes("сечение") ? 14 : 3;
  }
  if (lower.includes("треугольник") || lower.includes("трапеци") || lower.includes("параллелограмм") || lower.includes("окружност") || lower.includes("хорд") || lower.includes("касательн к окружност")) {
    return lower.includes("докажите, что") || lower.includes("пункт б") ? 17 : 1;
  }
  if (lower.includes("найдите корень уравнения") || lower.includes("решите уравнение")) {
    return 6;
  }
  if (lower.includes("найдите значение выражения")) {
    return 7;
  }
  if (lower.includes("неравенство") || lower.includes("решите неравенство")) {
    return 15;
  }
  if (lower.includes("натуральн") || lower.includes("целые числа") || lower.includes("делятся на") || lower.includes("простые числа")) {
    return 19;
  }
  return 1;
}

